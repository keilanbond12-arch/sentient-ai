export type Provider = "openai" | "claude" | "gemini" | "deepseek";
export type TaskMode = "auto" | "general" | "research" | "coding" | "game" | "creative" | "planning";

export const MODEL_LIMITS: Record<Provider, number> = {
  openai: 1000, claude: 1000, gemini: 910, deepseek: 1000
};

export const PROVIDER_MODELS: Record<Provider, string> = {
  openai: "openai/gpt-4.1",
  claude: "anthropic/claude-sonnet-4",
  gemini: "google/gemini-2.5-pro",
  deepseek: "deepseek/deepseek-chat"
};

export function chooseTaskMode(text: string): Exclude<TaskMode, "auto"> {
  const t = text.toLowerCase();
  if (/roblox|game|level|map|3d model|character|animation|luau|unity|unreal/.test(t)) return "game";
  if (/code|debug|program|javascript|typescript|python|api|website|app|script/.test(t)) return "coding";
  if (/image|picture|logo|illustration|design|thumbnail|artwork/.test(t)) return "creative";
  if (/research|latest|today|current|news|compare sources|find sources/.test(t)) return "research";
  if (/plan|roadmap|organize|project|steps|strategy/.test(t)) return "planning";
  return "general";
}

export function chooseProvider(text: string, mode: TaskMode): Provider {
  const t = text.toLowerCase();
  if (mode === "coding" || /debug|algorithm|code review/.test(t)) return "deepseek";
  if (mode === "game" || mode === "creative" || /image|visual|3d|model/.test(t)) return "gemini";
  if (mode === "planning" || /complex|deep reasoning|analyze thoroughly/.test(t)) return "claude";
  return "openai";
}

